"""Request and response models of the stories module. Messages shown to people are in Spanish."""

from __future__ import annotations

import re
from typing import Literal

from pydantic import BaseModel, Field, field_validator, model_validator

from lib.stories.constants import EPOCAS, NARRADOR_PROYECTO

MAX_TAGS = 6
MAX_PHOTOS = 6
MAX_TEXT = 5000
MAX_PLACE_NAME = 80


# ---- statistics --------------------------------------------------------------


class PorOrigen(BaseModel):
    comunidad: int
    proyecto: int


class PorFormato(BaseModel):
    foto: int
    audio: int
    video: int


class Estadisticas(BaseModel):
    """Counters for the header, the map cards and the admin summary."""

    publicadas: int
    en_revision: int
    rechazadas: int
    aprobadas_comunidad: int
    por_origen: PorOrigen
    sectores_con_historias: int
    total_sectores: int
    formatos: PorFormato


# ---- telling a story ---------------------------------------------------------


class UbicacionIn(BaseModel):
    lat: float = Field(ge=-90, le=90)
    lon: float = Field(ge=-180, le=180)


class MedioIn(BaseModel):
    tipo: Literal["foto", "audio", "video"]
    url: str = Field(max_length=500)
    mime: str | None = Field(None, max_length=60)
    bytes: int | None = Field(None, ge=0)
    duracion_s: int | None = Field(None, ge=0, le=3600)


class HistoriaIn(BaseModel):
    """What a narrator sends. Anything else (state, origin, author, code) is ignored: the server decides."""

    client_id: str  # generated by the phone; a resend with the same id never duplicates the story
    titulo: str
    texto: str = Field("", max_length=20000)
    epoca: str
    sector_id: str | None = Field(None, max_length=60)  # ignored: the server finds the sector from the point
    etiquetas: list[str] = Field(default_factory=list, max_length=20)
    ubicacion: UbicacionIn
    ubicacion_origen: Literal["gps", "mapa", "sector"]
    lugar_nombre: str | None = Field(None, max_length=200)  # optional name of the place, e.g. "Finca La Esperanza"
    medios: list[MedioIn] = Field(default_factory=list, max_length=20)

    @field_validator("lugar_nombre")
    @classmethod
    def clean_place_name(cls, value: str | None) -> str | None:
        name = re.sub(r"\s+", " ", value or "").strip()
        if not name:
            return None
        if len(name) > MAX_PLACE_NAME:
            raise ValueError(f"El nombre del lugar es muy largo (máximo {MAX_PLACE_NAME} letras).")
        return name

    @field_validator("client_id")
    @classmethod
    def check_client_id(cls, value: str) -> str:
        if not re.fullmatch(r"[A-Za-z0-9_-]{8,64}", value):
            raise ValueError("Identificador de envío no válido.")
        return value

    @field_validator("titulo")
    @classmethod
    def clean_title(cls, value: str) -> str:
        title = re.sub(r"\s+", " ", value).strip()
        if not 3 <= len(title) <= 120:
            raise ValueError("Ponle un título a tu historia (entre 3 y 120 letras).")
        return title

    @field_validator("texto")
    @classmethod
    def clean_text(cls, value: str) -> str:
        text = value.strip()
        if len(text) > MAX_TEXT:
            raise ValueError(f"La historia escrita es muy larga (máximo {MAX_TEXT} letras).")
        return text

    @field_validator("epoca")
    @classmethod
    def check_epoch(cls, value: str) -> str:
        if value not in EPOCAS:
            raise ValueError("Elige la época en que ocurrió.")
        return value

    @field_validator("etiquetas")
    @classmethod
    def check_tags(cls, value: list[str]) -> list[str]:
        tags = list(dict.fromkeys(tag.strip() for tag in value if tag.strip()))
        if len(tags) > MAX_TAGS or any(len(tag) > 40 for tag in tags):
            raise ValueError(f"Elige hasta {MAX_TAGS} etiquetas.")
        return tags

    @model_validator(mode="after")
    def check_content_and_media(self):
        kinds = [medio.tipo for medio in self.medios]
        if not self.texto and "audio" not in kinds:
            raise ValueError("Graba tu historia con tu voz o escríbela.")
        if kinds.count("audio") > 1 or kinds.count("video") > 1 or kinds.count("foto") > MAX_PHOTOS:
            raise ValueError(f"Puedes subir un audio, un video y hasta {MAX_PHOTOS} fotos.")
        return self


class HistoriaProyectoIn(HistoriaIn):
    """A story the team uploads (F12). It is published at once; the place is the center of the sector unless given."""

    ubicacion: UbicacionIn | None = None
    ubicacion_origen: Literal["gps", "mapa", "sector"] = "sector"
    narrador_nombre: str = NARRADOR_PROYECTO

    @field_validator("narrador_nombre")
    @classmethod
    def clean_narrator(cls, value: str) -> str:
        name = re.sub(r"\s+", " ", value).strip()
        if not 2 <= len(name) <= 80:
            raise ValueError("Escribe quién cuenta la historia (entre 2 y 80 letras).")
        return name


class HistoriaOut(BaseModel):
    codigo: str
    titulo: str
    estado: str
    enviada_en: str


class MedioPublico(BaseModel):
    """A file of a published story. `url` is empty in the example stories, which have no real file."""

    tipo: str
    url: str | None = None
    mime: str | None = None
    duracion_s: int | None = None


class HistoriaMapa(BaseModel):
    """What the map and its list need about a published story (no text, no author id)."""

    codigo: str
    titulo: str
    narrador_nombre: str
    sector_id: str | None = None  # None: another place of the zone
    lugar_nombre: str | None = None
    epoca: str
    formatos: list[str]
    origen: str
    lat: float
    lon: float
    aproximada: bool = False  # the point is rounded (about 500 m) to care for the privacy of whoever told it
    foto_url: str | None = None  # the first photo, for the thumbnail
    etiquetas: list[str] = []  # for the search box of the map
    publicada_en: str


class HistoriaPublica(HistoriaMapa):
    """The card (ficha) of a published story."""

    texto: str
    medios: list[MedioPublico]


class MedioAdmin(BaseModel):
    tipo: str
    url: str | None = None  # the example stories have no real file
    mime: str | None = None
    bytes: int | None = None
    duracion_s: int | None = None


class HistoriaAdmin(BaseModel):
    """A story as the administrators see it: all the content, to review or to read."""

    codigo: str
    titulo: str
    texto: str
    narrador_nombre: str
    sector_id: str | None = None
    lugar_nombre: str | None = None
    epoca: str
    etiquetas: list[str]
    formatos: list[str]
    medios: list[MedioAdmin]
    estado: str
    origen: str
    ejemplo: bool
    motivo_rechazo: str | None = None
    lat: float
    lon: float
    enviada_en: str
    revisada_en: str = ""
    publicada_en: str = ""


class AprobarIn(BaseModel):
    """The checks the administrator marked ("tema", "territorio", "datos")."""

    confirmaciones: list[str] = Field(default_factory=list, max_length=10)


class RechazarIn(BaseModel):
    motivo: str = Field(default="", max_length=60)  # the id of one of the rejection reasons


class HistoriaMia(BaseModel):
    codigo: str
    titulo: str
    sector_id: str | None = None  # None: another place of the zone
    lugar_nombre: str | None = None
    epoca: str
    formatos: list[str]
    estado: str
    motivo_rechazo: str | None = None
    enviada_en: str
